-- Run in the Supabase SQL editor. Safe to re-run: every statement is
-- "if not exists", so existing tables and data are left alone.
--
-- Existing installs only need the sections after the base tables.
-- Until they run, the app keeps working: budgets fall back to the BUDGETS /
-- MONTHLY_BUDGET env vars, and subscription renewals are not auto-logged.

-- ---------------------------------------------------------------------------
-- Base tables (fresh setup)
-- ---------------------------------------------------------------------------

create table if not exists txns (
    id         bigint generated by default as identity primary key,
    date       text not null,            -- YYYY-MM-DD (queried with LIKE 'YYYY-MM-%')
    category   text not null,
    amount     numeric not null,
    note       text not null default '',
    type       text not null default 'expense' check (type in ('expense', 'income')),
    chat_id    bigint not null,
    created_at timestamptz not null default now()
);
create index if not exists txns_chat_created_idx on txns (chat_id, created_at desc);
create index if not exists txns_date_idx on txns (date);

create table if not exists subscriptions (
    id         bigint generated by default as identity primary key,
    name       text not null,
    amount     numeric not null,
    cycle      text not null check (cycle in ('monthly', 'yearly')),
    chat_id    bigint not null,
    active     boolean not null default true,
    created_at timestamptz not null default now()
);

-- Rate limiting for Gemini-backed endpoints and login (lib/ratelimit.py).
create table if not exists api_requests (
    id          bigint generated by default as identity primary key,
    endpoint    text not null,
    client_hash text not null,
    created_at  timestamptz not null default now()
);
create index if not exists api_requests_lookup_idx on api_requests (endpoint, client_hash, created_at);

-- ---------------------------------------------------------------------------
-- Budgets editable from Telegram (/setbudget) and the dashboard.
-- category "_monthly" holds the overall monthly budget; amount 0 = no cap.
-- ---------------------------------------------------------------------------

create table if not exists budgets (
    category   text primary key,
    amount     numeric not null check (amount >= 0),
    updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Date of the last renewal the daily cron auto-logged for each subscription,
-- so a renewal is logged once per period even if you delete that entry.
-- ---------------------------------------------------------------------------

alter table subscriptions add column if not exists last_billed date;

-- The app connects with the service role key (SUPABASE_KEY), which bypasses
-- RLS; enabling it keeps the new table closed to the public anon key.
alter table budgets enable row level security;

-- ---------------------------------------------------------------------------
-- Loans & EMIs (/loans.html). Added and edited from the dashboard; EMIs and
-- lump-sum prepayments are recorded from Telegram ("home loan emi done").
-- `outstanding` is the principal still owed (or, for a loan with no interest
-- rate, the total still to pay) and moves with every payment.
-- ---------------------------------------------------------------------------

create table if not exists loans (
    id            bigint generated by default as identity primary key,
    name          text not null,
    lender        text not null default '',
    loan_type     text not null default 'other',
    principal     numeric not null check (principal > 0),
    interest_rate numeric check (interest_rate >= 0),        -- % per year; null = unknown
    emi_amount    numeric not null check (emi_amount > 0),
    tenure_months integer not null check (tenure_months > 0),
    emis_paid     integer not null default 0 check (emis_paid >= 0),
    outstanding   numeric not null check (outstanding >= 0),
    start_date    date,
    emi_day       integer check (emi_day between 1 and 31),
    notes         text not null default '',
    chat_id       bigint,
    created_at    timestamptz not null default now()
);

-- One row per EMI or prepayment, so each can be undone exactly.
create table if not exists loan_payments (
    id         bigint generated by default as identity primary key,
    loan_id    bigint not null references loans (id) on delete cascade,
    kind       text not null check (kind in ('emi', 'prepayment')),
    amount     numeric not null check (amount > 0),
    principal  numeric not null default 0,
    interest   numeric not null default 0,
    paid_on    date not null,
    note       text not null default '',
    chat_id    bigint,
    created_at timestamptz not null default now()
);
create index if not exists loan_payments_loan_idx on loan_payments (loan_id, paid_on desc);

-- ---------------------------------------------------------------------------
-- Money lent to / borrowed from friends (/friends.html). A ledger: a person's
-- balance is lent - received - borrowed + repaid (positive = they owe you).
-- ---------------------------------------------------------------------------

create table if not exists friend_txns (
    id         bigint generated by default as identity primary key,
    person     text not null,                -- stored lowercase
    kind       text not null check (kind in ('lent', 'borrowed', 'received', 'repaid')),
    amount     numeric not null check (amount > 0),
    note       text not null default '',
    date       date not null,
    chat_id    bigint,
    created_at timestamptz not null default now()
);
create index if not exists friend_txns_person_idx on friend_txns (person);

alter table loans enable row level security;
alter table loan_payments enable row level security;
alter table friend_txns enable row level security;
